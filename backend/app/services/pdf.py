"""Server-side PDF report generation (ReportLab) per spec §1.4."""
from __future__ import annotations

import io
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Spacer, Table, TableStyle, Paragraph
from typing import Any

HEADER_TEXT = "GSPC Pipavav Power Corporation Limited — Confidential"
FOOTER_TEXT = "Generated from PS000200 Reporting System"


def render_report(
    plant_name: str,
    unit_number: str,
    period_text: str,
    parameters_selected: str,
    generated_by: str,
    rows: list[dict[str, Any]],
) -> bytes:
    buffer = io.BytesIO()

    styles = getSampleStyleSheet()
    header_style = ParagraphStyle(
        "reportHeader", parent=styles["Title"], fontSize=13, textColor=colors.HexColor("#0F4C81")
    )
    subheader_style = ParagraphStyle(
        "reportSubHeader", parent=styles["Normal"], fontSize=9, textColor=colors.HexColor("#475569")
    )
    generated_at = datetime.now(timezone.utc).strftime("%d %b %Y %H:%M UTC")

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
        title=HEADER_TEXT,
    )

    def _footer(canvas, doc_) -> None:  # every page
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#64748B"))
        canvas.drawString(18 * mm, 12 * mm, FOOTER_TEXT)
        canvas.drawRightString(A4[0] - 18 * mm, 12 * mm, f"Page {canvas.getPageNumber()}")
        canvas.restoreState()

    story: list = [
        Paragraph(HEADER_TEXT, header_style),
        Spacer(1, 4),
        Paragraph(
            f"Plant: {plant_name} &nbsp;·&nbsp; Unit: {unit_number} &nbsp;·&nbsp; Period: {period_text}",
            subheader_style,
        ),
        Paragraph(
            f"Parameters: {parameters_selected}", subheader_style
        ),
        Paragraph(f"Generated by: {generated_by} &nbsp;·&nbsp; Generated at: {generated_at}", subheader_style),
        Spacer(1, 10),
    ]

    if rows:
        table_data: list[list] = [["Date", "Parameter", "Value", "UoM"]]
        for row in rows:
            table_data.append(
                [
                    row["recorded_date"].isoformat(),
                    row["parameter"],
                    f"{row['value']:,.4f}".rstrip("0").rstrip(".") if row["value"] % 1 else f"{row['value']:,.0f}",
                    row["uom"] or "",
                ]
            )
        table = Table(
            table_data,
            colWidths=[30 * mm, 55 * mm, 35 * mm, 35 * mm],
            repeatRows=1,
        )
        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0F4C81")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F1F5F9")]),
                    ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#CBD5E1")),
                    ("ALIGN", (2, 1), (3, -1), "RIGHT"),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                ]
            )
        )
        story.append(table)
    else:
        story.append(Paragraph("No data found for the selected criteria.", styles["Normal"]))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()
